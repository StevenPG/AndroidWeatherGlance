#!/usr/bin/env python3
"""Generates the app's weather-condition vector drawables.

The icons share geometry (a single cloud outline, sun, moon, precipitation marks) so they stay
visually consistent. Run from the repo root and commit the output:

    python3 tools/generate_weather_icons.py
"""
import math
from pathlib import Path

RES = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"

SUN = "#FFB300"
SUN_HOT = "#FF7043"
MOON = "#FFD54F"
CLOUD_LIGHT = "#B0BEC5"
CLOUD = "#90A4AE"
CLOUD_DARK = "#78909C"
RAIN = "#42A5F5"
SNOW = "#4FC3F7"
ICE = "#26C6DA"
BOLT = "#FFC107"
WHITE = "#FFFFFFFF"

CLOUD_PATH = "M14,36 h22 a8,8 0,0 0,0.9 -15.95 A11,11 0,0 0,15.4 19.2 A8.5,8.5 0,1 0,14 36 Z"
MOON_PATH = "M28,9 A15,15 0,1 0,39,30 A12,12 0,0 1,28,9 Z"


def fill(d, color):
    return f'    <path android:fillColor="{color}" android:pathData="{d}" />'


def stroke(d, color, width=2.6):
    return (
        f'    <path android:strokeColor="{color}" android:strokeWidth="{width}" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}" />'
    )


def group(body, tx=0.0, ty=0.0, scale=1.0):
    return (
        f'    <group android:translateX="{tx}" android:translateY="{ty}" '
        f'android:scaleX="{scale}" android:scaleY="{scale}">\n{body}\n    </group>'
    )


def circle(cx, cy, r):
    return f"M{cx - r},{cy} a{r},{r} 0,1 0,{2 * r},0 a{r},{r} 0,1 0,{-2 * r},0 Z"


def sun(cx, cy, r, ray_in, ray_out, color=SUN, width=2.6):
    rays = []
    for i in range(8):
        a = math.radians(i * 45)
        x1, y1 = cx + ray_in * math.cos(a), cy + ray_in * math.sin(a)
        x2, y2 = cx + ray_out * math.cos(a), cy + ray_out * math.sin(a)
        rays.append(f"M{x1:.2f},{y1:.2f} L{x2:.2f},{y2:.2f}")
    return "\n".join([fill(circle(cx, cy, r), color), stroke(" ".join(rays), color, width)])


def cloud(color=CLOUD, tx=0.0, ty=0.0, scale=1.0):
    return group(fill(CLOUD_PATH, color), tx, ty, scale)


def drops(xs, color=RAIN, top=33, bottom=41):
    return stroke(" ".join(f"M{x},{top} L{x - 2.5},{bottom}" for x in xs), color)


def dots(points, color=SNOW, r=2.2):
    return fill(" ".join(circle(x, y, r) for x, y in points), color)


def snowflake(color=SNOW):
    parts = []
    for i in range(6):
        a = math.radians(i * 60 - 90)
        ex, ey = 24 + 17 * math.cos(a), 24 + 17 * math.sin(a)
        parts.append(f"M24,24 L{ex:.2f},{ey:.2f}")
        bx, by = 24 + 11 * math.cos(a), 24 + 11 * math.sin(a)
        for side in (-1, 1):
            b = a + side * math.radians(40)
            parts.append(f"M{bx:.2f},{by:.2f} L{bx + 5 * math.cos(b):.2f},{by + 5 * math.sin(b):.2f}")
    return stroke(" ".join(parts), color, 2.8)


def vector(body, size=48):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/generate_weather_icons.py. Do not edit by hand. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
        '    android:viewportWidth="48"\n    android:viewportHeight="48">\n'
        f"{body}\n</vector>\n"
    )


def partly_cloudy_day(cloud_color=CLOUD_LIGHT, sun_color=SUN):
    return "\n".join([sun(17, 16, 6.5, 9.5, 12.5, sun_color), cloud(cloud_color, 11, 13, 0.78)])


ICONS = {
    "ic_wx_clear_day": sun(24, 24, 9, 13, 18.5),
    "ic_wx_hot": sun(24, 24, 9, 13, 18.5, SUN_HOT),
    "ic_wx_clear_night": fill(MOON_PATH, MOON),
    "ic_wx_partly_cloudy_day": partly_cloudy_day(),
    "ic_wx_partly_cloudy_night": "\n".join(
        [group(fill(MOON_PATH, MOON), 1, 0, 0.62), cloud(CLOUD_LIGHT, 11, 13, 0.78)]
    ),
    "ic_wx_mostly_cloudy": "\n".join([sun(14, 13, 6, 9, 11.5), cloud(CLOUD, 2, 2)]),
    "ic_wx_cloudy": "\n".join([cloud(CLOUD_LIGHT, 6, -2, 0.8), cloud(CLOUD, 0, 3)]),
    "ic_wx_rain": "\n".join([cloud(CLOUD_DARK, 0, -6), drops([16, 24, 32])]),
    "ic_wx_showers": "\n".join([sun(37, 11, 5, 7.5, 9.5), cloud(CLOUD, -2, -5), drops([19, 28])]),
    "ic_wx_thunderstorm": "\n".join(
        [
            cloud(CLOUD_DARK, 0, -6),
            fill("M26,27 L18,38 H23.5 L20,46 L31,34 H25.5 L29.5,27 Z", BOLT),
            drops([13, 38], top=33, bottom=39),
        ]
    ),
    "ic_wx_snow": "\n".join(
        [cloud(CLOUD, 0, -6), dots([(15, 35), (24, 35), (33, 35), (19.5, 42), (28.5, 42)])]
    ),
    "ic_wx_sleet": "\n".join(
        [cloud(CLOUD, 0, -6), drops([15, 31], top=33, bottom=40), dots([(22, 37), (37, 37), (26, 44)])]
    ),
    "ic_wx_freezing_rain": "\n".join(
        [cloud(CLOUD_DARK, 0, -6), drops([16, 24, 32], ICE, 33, 40), dots([(12.5, 44.5), (20.5, 44.5), (28.5, 44.5)], ICE, 1.6)]
    ),
    "ic_wx_fog": "\n".join(
        [cloud(CLOUD_LIGHT, 0, -8), stroke("M8,32 H40 M12,38 H44 M6,44 H34", CLOUD_DARK, 3)]
    ),
    "ic_wx_haze": "\n".join(
        [sun(24, 17, 7.5, 11, 14), stroke("M8,30 H40 M12,36 H44 M6,42 H36", CLOUD, 3)]
    ),
    "ic_wx_wind": stroke(
        "M6,17 H29 a5,5 0,1 0,-5,-5 M6,25 H37 a5,5 0,1 1,-5,5 M6,33 H21 a4,4 0,1 1,-4,4", CLOUD_DARK, 3
    ),
    "ic_wx_cold": snowflake(),
    "ic_wx_hurricane": "\n".join(
        [
            stroke(circle(24, 24, 5), CLOUD_DARK, 3.5),
            stroke("M24,19 C24,11 31,7 38,8 M24,29 C24,37 17,41 10,40", CLOUD_DARK, 3.5),
        ]
    ),
    "ic_wx_tornado": stroke(
        "M7,9 H41 M11,16 H39 M15,23 H35 M18,30 H31 M20,37 H27 M22,43 H24", CLOUD_DARK, 3.2
    ),
}

# Monochrome status-bar / themed-icon variants (alpha only).
STATUS_ICONS = {
    "ic_stat_weather": partly_cloudy_day(WHITE, WHITE),
    "ic_stat_alert": (
        '    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" '
        'android:pathData="M24,5 L45,41 H3 Z M22,17 H26 V30 H22 Z M22,33 H26 V37 H22 Z" />'
    ),
}


def launcher_foreground(cloud_color, sun_color):
    # 108dp adaptive canvas; keep artwork inside the 66dp safe zone.
    body = partly_cloudy_day(cloud_color, sun_color).replace("\n", "\n    ")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/generate_weather_icons.py. Do not edit by hand. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        '    <group android:translateX="25" android:translateY="25" android:scaleX="1.2" android:scaleY="1.2">\n'
        f"    {body}\n    </group>\n</vector>\n"
    )


def main():
    RES.mkdir(parents=True, exist_ok=True)
    for name, body in ICONS.items():
        (RES / f"{name}.xml").write_text(vector(body))
    for name, body in STATUS_ICONS.items():
        (RES / f"{name}.xml").write_text(vector(body, size=24))
    (RES / "ic_launcher_foreground.xml").write_text(launcher_foreground("#ECEFF1", SUN))
    (RES / "ic_launcher_monochrome.xml").write_text(launcher_foreground(WHITE, WHITE))
    print(f"Wrote {len(ICONS) + len(STATUS_ICONS) + 2} drawables to {RES}")


if __name__ == "__main__":
    main()
